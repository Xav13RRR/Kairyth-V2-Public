  function lookup(dict, key) {
    const parts = String(key).split(".");
    let cur = dict;
    for (const p of parts) {
      if (cur == null || typeof cur !== "object") return null;
      cur = cur[p];
    }
    return typeof cur === "string" ? cur : null;
  }

  function interpolate(template, vars) {
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
  }

  function getLang() {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === "en" ? "en" : "zh";
  }

  function setLang(lang) {
    const next = lang === "en" ? "en" : "zh";
    localStorage.setItem(STORAGE_KEY, next);
    document.documentElement.lang = next === "en" ? "en" : "zh-CN";
    applyDom();
    window.dispatchEvent(new CustomEvent("mka:langchange", { detail: { lang: next } }));
    return next;
  }

  function t(key, vars) {
    const lang = getLang();
    const dict = lang === "en" ? LOCALE_EN : LOCALE_ZH;
    const raw = lookup(dict, key) || lookup(LOCALE_ZH, key) || key;
    return interpolate(raw, vars);
  }

  function translateApi(text) {
    if (!text || getLang() === "zh") return text;
    const s = String(text);
    if (API_EXACT[s]) return API_EXACT[s];
    for (const [zh, en] of API_PREFIX) {
      if (s.includes(zh)) return s.replace(zh, en);
    }
    return s;
  }

  function applyDom(root) {
    const el = root || document;
    el.querySelectorAll("[data-i18n]").forEach((node) => {
      const key = node.getAttribute("data-i18n");
      if (key) node.textContent = t(key);
    });
    el.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      const key = node.getAttribute("data-i18n-placeholder");
      if (key) node.placeholder = t(key);
    });
    el.querySelectorAll("[data-i18n-title]").forEach((node) => {
      const key = node.getAttribute("data-i18n-title");
      if (key) node.title = t(key);
    });
    const titleKey = document.querySelector("title")?.getAttribute("data-i18n");
    if (titleKey) document.title = t(titleKey);
  }

  function onChange(cb) {
    window.addEventListener("mka:langchange", (ev) => cb(ev.detail?.lang));
  }

  document.documentElement.lang = getLang() === "en" ? "en" : "zh-CN";

